#DICE GAME
import random

side1 = [[" ", " ", " "], 
         [" ", "*", " "],
         [" ", " ", " "]]

side2 = [[" ", "*", " "],
         [" ", " ", " "],
         [" ", "*", " "]]

side3 = [[" ", "*", " "],
         [" ", "*", " "],
         [" ", "*", " "]]

side4 = [["*", " ", "*"], 
         [" ", " ", " "],
         ["*", " ", "*"]]

side5 = [["*", " ", "*"], 
         [" ", "*", " "],
         ["*", " ", "*"]]

side6 = [["*", " ", "*"], 
         ["*", " ", "*"],
         ["*", " ", "*"]]

dice = [side1, side2, side3, side4, side5, side6]

roll = random.choice(dice)
print("---------")
for side in roll:
    print("|", " ".join(side), "|")
print("---------")